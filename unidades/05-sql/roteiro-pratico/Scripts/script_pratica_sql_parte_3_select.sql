     , PRO.NOME_PRODUTO
     , UE.DESCRICAO_UNIDADE_MEDIDA
     , PRO.PRECO_PRODUTO
     , PRO.QUANTIDADE_ESTOQUE
     , SUM(PED.VALOR_TOTAL) TOTAL_VENDIDO
     , ( SELECT SUM(PED.VALOR_TOTAL) AS TOTAL_VENDIDO
                                   FROM PEDIDOS PED
                                  INNER JOIN ITENS_PEDIDOS ITE
                                  ON PED.CODIGO_PEDIDO = ITE.CODIGO_PEDIDO
                                  INNER JOIN PRODUTOS PRO
                                  ON ITE.CODIGO_PRODUTO = PRO.CODIGO_PRODUTO
