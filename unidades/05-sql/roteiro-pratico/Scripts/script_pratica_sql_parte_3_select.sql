        , PRO.NOME_PRODUTO
        , UE.DESCRICAO_UNIDADE_MEDIDA
        , PRO.PRECO_PRODUTO
        , PRO.QUANTIDADE_ESTOQUE
 HAVING SUM(PED.VALOR_TOTAL) > ( SELECT SUM(PED.VALOR_TOTAL) AS TOTAL_VENDIDO
                                   FROM PEDIDOS PED
