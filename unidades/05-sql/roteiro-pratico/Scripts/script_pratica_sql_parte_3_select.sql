  FROM PRODUTOS PRO
  INNER JOIN UNIDADE_MEDIDA UE
  ON PRO.CODIGO_UNIDADE_MEDIDA = UE.CODIGO_UNIDADE_MEDIDA
  INNER JOIN ITENS_PEDIDOS ITE
  ON ITE.CODIGO_PRODUTO = PRO.CODIGO_PRODUTO
  INNER JOIN PEDIDOS PED
  ON ITE.CODIGO_PEDIDO = PED.CODIGO_PEDIDO
